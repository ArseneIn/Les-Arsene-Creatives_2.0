/**
 * Generates a dynamic 10-Fast-Fingers style text from a given word pool.
 * It randomly formats words:
 * - 12% probability: Capitalize the first letter (e.g. "Strategy", "Arrive")
 * - 6% probability: Convert the entire word to ALL CAPS (e.g. "TAX")
 * - Otherwise: Keep standard lowercase.
 */
export function generate10FastFingersText(wordPool: string[], count = 150): string {
    if (!wordPool || wordPool.length === 0) return '';
    const generated: string[] = [];
    for (let i = 0; i < count; i++) {
        const randomIndex = Math.floor(Math.random() * wordPool.length);
        let word = wordPool[randomIndex].toLowerCase();
        
        const rand = Math.random();
        if (rand < 0.12) {
            // 12% probability: Capitalize first letter
            word = word.charAt(0).toUpperCase() + word.slice(1);
        } else if (rand < 0.18) {
            // 6% probability (0.18 - 0.12): Convert to ALL CAPS
            word = word.toUpperCase();
        }
        
        generated.push(word);
    }
    return generated.join(' ');
}

